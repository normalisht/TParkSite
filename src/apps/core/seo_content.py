def _is_empty(value) -> bool:
    return value is None or value == ""


def fill_seo_content(site_settings_model, category_model) -> None:
    site, _ = site_settings_model.objects.get_or_create(pk=1)
    changed = [field for field, value in SITE_SETTINGS.items() if _is_empty(getattr(site, field))]
    for field in changed:
        setattr(site, field, SITE_SETTINGS[field])
    if changed:
        site.save(update_fields=changed)

    for category in category_model.objects.filter(slug__in=CATEGORIES):
        title, description = CATEGORIES[category.slug]
        fields = []
        if not category.seo_title:
            category.seo_title, fields = title, [*fields, "seo_title"]
        if not category.seo_description:
            category.seo_description, fields = description, [*fields, "seo_description"]
        if fields:
            category.save(update_fields=[*fields, "updated_at"])


def _update_seo(model, texts: dict, outdated: dict | None = None) -> None:
    for obj in model.objects.filter(slug__in=texts):
        previous = (outdated or {}).get(obj.slug, ("", ""))
        changed = []
        for field, new, old in zip(("seo_title", "seo_description"), texts[obj.slug], previous, strict=True):
            if getattr(obj, field) in ("", old):
                setattr(obj, field, new)
                changed.append(field)
        if changed:
            obj.save(update_fields=[*changed, "updated_at"])


def refresh_seo_content(site_settings_model, category_model, service_model, event_model, info_page_model) -> None:
    site, _ = site_settings_model.objects.get_or_create(pk=1)
    changed = [field for field, old in OUTDATED_SITE_SETTINGS.items() if getattr(site, field) == old]
    if _is_empty(site.price_range):
        changed.append("price_range")
    for field in changed:
        setattr(site, field, SITE_SETTINGS[field])
    if changed:
        site.save(update_fields=[*changed, "updated_at"])

    _update_seo(category_model, CATEGORIES, OUTDATED_CATEGORIES)
    _update_seo(service_model, SERVICES)
    _update_seo(event_model, EVENTS)
    _update_seo(info_page_model, INFO_PAGES)


def fill_default_og_image(site_settings_model) -> None:
    """Своя копия файла, а не ссылка на фото галереи: удаление фото из галереи стёрло бы и картинку для соцсетей."""
    site, _ = site_settings_model.objects.get_or_create(pk=1)
    if site.og_image or not default_storage.exists(DEFAULT_OG_IMAGE_SOURCE):
        return
    with default_storage.open(DEFAULT_OG_IMAGE_SOURCE, "rb") as source:
        name = PurePosixPath(DEFAULT_OG_IMAGE_SOURCE).name
        site.og_image = default_storage.save(f"seo/{name}", source)
    site.save(update_fields=["og_image", "updated_at"])
